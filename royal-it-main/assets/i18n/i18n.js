  function hasLatin(text) {
    return /[A-Za-z]/.test(text || '');
  }

  function isNonTranslatable(text) {
    const clean = normalizeText(text);
    if (!clean) return true;
    if (/^[\d\s+.,:%/()\-–—|&!*©]+$/.test(clean)) return true;
    if (/^[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}$/.test(clean)) return true;
    if (/^(https?:|www\.|mailto:|tel:)/i.test(clean)) return true;
    return false;
  }

  function fallbackArabic(text) {
    let out = String(text || '');
    Object.keys(PHRASE_TRANSLATIONS).sort((a, b) => b.length - a.length).forEach((key) => {
      const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      out = out.replace(new RegExp(escaped, 'gi'), PHRASE_TRANSLATIONS[key]);
    });
    out = out.replace(/[A-Za-z][A-Za-z0-9&'’/.-]*/g, function (word) {
      const key = word.toLowerCase().replace(/[.,:;!?]+$/g, '');
      return WORD_TRANSLATIONS[key] || '';
    });
    out = out.replace(/\s{2,}/g, ' ').replace(/\s+([،.؟:;!])/g, '$1').trim();
    if (!out || hasLatin(out)) {
      const low = String(text || '').toLowerCase();
      if (/policy|agreement|terms|privacy|refund|hosting|legal|nda/.test(low)) return 'محتوى قانوني تجريبي';
      if (/contact|email|phone|address|inquiry|form|name/.test(low)) return 'معلومات تواصل تجريبية';
      if (/team|developer|manager|officer|advisor|director|ceo|marketing/.test(low)) return 'فريق العمل التجريبي';
      if (/service|software|web|app|cloud|digital|ai|automation|crm|pos|pms|it/.test(low)) return 'حلول تقنية رقمية';
      if (/project|client|business|growth|support/.test(low)) return 'محتوى أعمال تجريبي';
      return 'محتوى تجريبي';
    }
    return out;
  }

  function getTranslation(key) {
    const clean = normalizeText(key);
    if (!clean || i18next.language !== 'ar' || isNonTranslatable(clean)) return key;
    const exact = (resources.ar && resources.ar.translation && resources.ar.translation[clean]) || PHRASE_TRANSLATIONS[clean];
    if (exact && exact !== clean) return exact;
    return fallbackArabic(clean);
  }

  function translateTextNode(node) {
    const original = node.__i18nOriginal || node.nodeValue;
    if (!node.__i18nOriginal) node.__i18nOriginal = original;
    const clean = normalizeText(original);
    if (!clean) return;
    if (i18next.language === 'ar') {
      const translated = getTranslation(clean);
      node.nodeValue = original.replace(clean, translated);
    } else {
      node.nodeValue = original;
    }
  }

  function translateAttributes() {
    document.querySelectorAll('[placeholder], [title], [alt], [value]').forEach((el) => {
      ['placeholder', 'title', 'alt'].forEach((attr) => {
        if (!el.hasAttribute(attr)) return;
        const raw = el.getAttribute(attr);
        const keyName = '__i18n_' + attr;
        if (!el[keyName]) el[keyName] = raw;
        const original = el[keyName];
        const clean = normalizeText(original);
        const translated = getTranslation(clean);
        el.setAttribute(attr, i18next.language === 'ar' ? translated : original);
      });
    });
  }

  function translateManualKeys() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!el.__i18nOriginalHTML) el.__i18nOriginalHTML = el.innerHTML;
      el.innerHTML = i18next.language === 'ar' ? getTranslation(key) : el.__i18nOriginalHTML;
    });
  }

  function translateVisibleText() {
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode(node) {
          const parent = node.parentElement;
          if (!parent || EXCLUDED_TAGS.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
          if (!normalizeText(node.nodeValue)) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
  }

  function setDirection(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.classList.toggle('rtl-mode', lang === 'ar');
    document.body.classList.toggle('ltr-mode', lang !== 'ar');
  }

  function setActiveButton(lang) {
    document.querySelectorAll('[data-lang-btn]').forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang-btn') === lang);
    });
    document.querySelectorAll('[data-current-lang]').forEach((label) => {
      label.textContent = lang === 'ar' ? 'AR' : 'EN';
    });
    document.querySelectorAll('.language-current').forEach((btn) => {
      btn.setAttribute('aria-expanded', 'false');
    });
    document.querySelectorAll('.language-switcher').forEach((box) => {
      box.classList.remove('open');
    });
  }

  function updateContent() {
    const lang = i18next.language || DEFAULT_LANG;
    setDirection(lang);
    translateManualKeys();
    translateVisibleText();
    translateAttributes();
    document.title = lang === 'ar' ? getTranslation(document.__i18nTitle || document.title) : (document.__i18nTitle || document.title);
    setActiveButton(lang);

    // Reset partner logo slider after RTL/LTR language changes.
    if (typeof window.resetPartnerSlider === 'function') {
      window.resetPartnerSlider();
    }
  }

  window.changeLanguage = function (lang) {
    i18next.changeLanguage(lang, function () {
      localStorage.setItem(STORAGE_KEY, lang);
      updateContent();
    });
  };

  function bindLanguageDropdowns() {
    document.querySelectorAll('.language-current').forEach((button) => {
      button.addEventListener('click', function (event) {
        event.preventDefault();
        event.stopPropagation();
        const wrapper = button.closest('.language-switcher');
        const willOpen = !wrapper.classList.contains('open');
        document.querySelectorAll('.language-switcher').forEach((box) => box.classList.remove('open'));
        wrapper.classList.toggle('open', willOpen);
        button.setAttribute('aria-expanded', String(willOpen));
      });
    });

    document.addEventListener('click', function () {
      document.querySelectorAll('.language-switcher').forEach((box) => box.classList.remove('open'));
      document.querySelectorAll('.language-current').forEach((button) => button.setAttribute('aria-expanded', 'false'));
    });
  }

  window.addEventListener('DOMContentLoaded', function () {
    document.__i18nTitle = document.title;
    bindLanguageDropdowns();
    i18next.init({ lng: DEFAULT_LANG, fallbackLng: 'en', resources }, updateContent);
  });
